import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

// Retain only building dimensions from the map update; no replacement geometry.
const sourceCommit = "d60597965aa3e0dd8b77b3bd087da50c21ae3d37";
const source = execFileSync("git", ["show", `${sourceCommit}:src/game/real-campus-data.ts`], {
  encoding: "utf8",
  maxBuffer: 20_000_000,
});
const profiles = JSON.parse(source.match(/export const REAL_CAMPUS_BUILDINGS = (.*) as const;/)[1]);
const classic = JSON.parse(readFileSync("src/osm-map-data.ts", "utf8").match(/export const osmRegions = (.*) as const;/)[1]);
const keys = new Set(classic.main.buildings.map(building => `${building.osmType}/${building.osmId}`));
const rows = profiles.filter(profile => keys.has(profile.key)).map(profile => {
  if (!(Number.isFinite(profile.heightMeters) && profile.heightMeters > 0))
    throw new Error(`Invalid height for ${profile.key}`);
  return `  ${JSON.stringify(profile.key)}: [${profile.heightMeters}, ${JSON.stringify(profile.confidence)}],`;
});
writeFileSync("src/game/building-height-data.ts", [
  `// Dimensions retained from ${sourceCommit} (v0.4.4).`,
  "// Generated by scripts/build-building-heights.mjs. OSM-derived and estimated values",
  "// retain their original confidence; estimates are not surveyed measurements.",
  'export const BUILDING_HEIGHTS: Readonly<Record<string, readonly [metres: number, source: "osm" | "estimated"]>> = {',
  ...rows,
  "};",
  "",
].join("\n"));
console.log(`Retained ${rows.length} building heights; classic map geometry is unchanged.`);
